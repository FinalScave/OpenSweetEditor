package com.qiplat.sweeteditor.core.config;

public final class HandleHitArea {
    public float left = 0f;
    public float top = 0f;
    public float right = 0f;
    public float bottom = 0f;

    public HandleHitArea() {
    }

    public HandleHitArea(float left, float top, float right, float bottom) {
        this.left = left;
        this.top = top;
        this.right = right;
        this.bottom = bottom;
    }
}
