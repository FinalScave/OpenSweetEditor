    private void UpdateSummary()
    {
        TextPosition cursor = controller.GetCursorPosition();
        string wrapLabel = wrapMode switch
        {
            WrapMode.WORD_BREAK => "W",
            WrapMode.CHAR_BREAK => "C",
            _ => "N",
        };
        string backendLabel = decorationProvider.HighlightBackendLabel.Contains("native", StringComparison.OrdinalIgnoreCase)
            ? "SweetLine"
            : decorationProvider.HighlightBackendLabel;
        string sampleName = activeSample == null ? "Sample" : System.IO.Path.GetFileNameWithoutExtension(activeSample.FileName);
        string perfLabel = perfOverlayEnabled ? " | FPS" : string.Empty;
        string nextValue = $"{sampleName} | {currentLanguageId} | {backendLabel} | {wrapLabel} | {currentScale * 100:F0}% | {cursor.Line + 1}:{cursor.Column + 1}{perfLabel}";
        if (string.Equals(lastSummaryValue, nextValue, StringComparison.Ordinal))
            return;

        lastSummaryValue = nextValue;
        summaryText.Text = nextValue;
    }

    private void ScheduleChromeRefresh(DeferredChromeWork work)
    {
        ScheduleChromeRefresh(work, DispatcherPriority.Background);
    }

    private void ScheduleChromeRefresh(DeferredChromeWork work, DispatcherPriority priority)
    {
        pendingChromeWork |= work;
        if (chromeRefreshScheduled)
            return;

        chromeRefreshScheduled = true;
        Dispatcher.UIThread.Post(ApplyScheduledChromeRefresh, priority);
    }

    private void ApplyScheduledChromeRefresh()
    {
        chromeRefreshScheduled = false;
        DeferredChromeWork work = pendingChromeWork;
        pendingChromeWork = DeferredChromeWork.None;

        if ((work & DeferredChromeWork.SamplePickerPopup) != 0 && samplePickerPopup.IsVisible)
            RepositionSamplePickerPopup();

        if ((work & DeferredChromeWork.Summary) != 0)
            UpdateSummary();
    }

