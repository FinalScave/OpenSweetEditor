    private Control BuildSamplePickerItem(DemoSampleFile sample, bool isSelected)
    {
        uint foreground = darkTheme ? 0xFFD7DEE9u : 0xFF1F2937u;
        uint secondary = darkTheme ? 0xFF7A8494u : 0xFF8A94A6u;
        uint background = isSelected
            ? (darkTheme ? 0xFF2A3A52u : 0xFFE4F0FFu)
            : (darkTheme ? 0xFF1B1E24u : 0xFFFFFFFFu);
        uint border = isSelected
            ? (darkTheme ? 0xFF4C9DFFu : 0xFF0F7AD9u)
            : (darkTheme ? 0xFF313844u : 0xFFD7DEE8u);
        string detail = sample.LanguageId;

        Grid row = new()
        {
            ColumnDefinitions = new ColumnDefinitions("*,Auto"),
            ColumnSpacing = 8,
            HorizontalAlignment = HorizontalAlignment.Stretch,
            VerticalAlignment = VerticalAlignment.Center,
        };
        row.Children.Add(new TextBlock
        {
            Text = sample.FileName,
            FontSize = 12.5,
            FontWeight = isSelected ? FontWeight.SemiBold : FontWeight.Medium,
            Foreground = CreateBrush(foreground),
            TextTrimming = TextTrimming.CharacterEllipsis,
            VerticalAlignment = VerticalAlignment.Center,
        });

        TextBlock detailText = new()
        {
            Text = detail,
            FontSize = 10.5,
            Foreground = CreateBrush(secondary),
            VerticalAlignment = VerticalAlignment.Center,
            TextAlignment = TextAlignment.Right,
        };
        Grid.SetColumn(detailText, 1);
        row.Children.Add(detailText);

        Border chrome = new()
        {
            Padding = new Thickness(10, 8),
            CornerRadius = new CornerRadius(10),
            Background = CreateBrush(background),
            BorderBrush = CreateBrush(border),
            BorderThickness = new Thickness(1),
            Child = row,
        };

        Button button = new()
        {
            Background = Brushes.Transparent,
            BorderBrush = Brushes.Transparent,
            BorderThickness = new Thickness(0),
            Padding = new Thickness(0),
            HorizontalAlignment = HorizontalAlignment.Stretch,
            HorizontalContentAlignment = HorizontalAlignment.Stretch,
            Content = chrome,
        };
        button.Click += (_, _) =>
        {
            HideSamplePickerPopup();
            if (!string.Equals(activeSample?.FileName, sample.FileName, StringComparison.Ordinal))
                _ = sampleLoader.LoadSampleAsync(sample);
        };
        return button;
    }

    private void RepositionSamplePickerPopup()
    {
        if (!samplePickerPopup.IsVisible)
            return;

        if (!TryGetControlBoundsInLayoutRoot(toolbarController.SamplePickerButton, out AvaloniaRect buttonBounds))
            return;

        double margin = 8;
        double rootWidth = layoutRoot.Bounds.Width;
        double rootHeight = layoutRoot.Bounds.Height;
        if (rootWidth <= 0 || rootHeight <= 0)
            return;

        double maxWidth = Math.Max(160, rootWidth - margin * 2);
        double width = Math.Clamp(Math.Max(buttonBounds.Width, 220), 160, maxWidth);
        samplePickerPopup.Width = width;
        samplePickerPopup.MaxHeight = Math.Max(120, Math.Min(SamplePickerPopupMaxHeight, rootHeight - buttonBounds.Bottom - margin * 2));
        samplePickerPopup.Measure(new AvaloniaSize(width, double.PositiveInfinity));

        double x = Math.Clamp(buttonBounds.X, margin, Math.Max(margin, rootWidth - width - margin));
        double y = Math.Max(margin, buttonBounds.Bottom + 4);
        samplePickerPopup.Margin = new Thickness(x, y, 0, 0);
    }

    private bool TryGetControlBoundsInLayoutRoot(Control control, out AvaloniaRect bounds)
    {
        bounds = default;
        Point? origin = control.TranslatePoint(default, layoutRoot);
        if (!origin.HasValue)
            return false;

        bounds = new AvaloniaRect(origin.Value, control.Bounds.Size);
        return bounds.Width > 0 && bounds.Height > 0;
    }

    private void OnMainViewPointerPressed(object? sender, PointerPressedEventArgs e)
    {
        if (!samplePickerPopup.IsVisible)
            return;

        Point point = e.GetPosition(layoutRoot);
        bool insideButton = TryGetControlBoundsInLayoutRoot(toolbarController.SamplePickerButton, out AvaloniaRect buttonBounds) &&
                            buttonBounds.Contains(point);
        bool insidePopup = TryGetControlBoundsInLayoutRoot(samplePickerPopup, out AvaloniaRect popupBounds) &&
                           popupBounds.Contains(point);
        if (!insideButton && !insidePopup)
            HideSamplePickerPopup();
    }

    private void MaybeShowInlineSuggestion(TextPosition cursor)
    {
        CancelPendingInlineSuggestion();
        if (!allowPassiveInlineSuggestion || !inlineSuggestionAutoEnabled || controller.IsInlineSuggestionShowing())
            return;

        (bool hasSelection, _) = controller.GetSelection();
        if (hasSelection)
            return;

        Document? doc = controller.GetDocument();
        if (doc == null)
            return;

        string lineText = doc.GetLineText(cursor.Line) ?? string.Empty;
        if (lineText.Trim().Length == 0 || cursor.Column != lineText.Length)
            return;

        int token = ++pendingInlineSuggestionToken;
        DispatcherTimer.RunOnce(() =>
        {
            if (token != pendingInlineSuggestionToken || controller.IsInlineSuggestionShowing())
                return;

            controller.ShowInlineSuggestion(new InlineSuggestion(cursor.Line, cursor.Column, InlineSuggestionText));
            ScheduleChromeRefresh(DeferredChromeWork.Summary);
        }, TimeSpan.FromMilliseconds(OperatingSystem.IsAndroid() ? 1000 : 700));
    }

    private void ApplyToolbarChrome(uint foreground, uint surfaceMuted, uint border, uint accent)
    {
        foreach (Button button in toolbarController.ActionButtons)
        {
            button.Foreground = CreateBrush(foreground);
            button.Background = Brushes.Transparent;
            button.BorderBrush = Brushes.Transparent;

            if (button.Content is Border chrome)
            {
                bool active = ReferenceEquals(button, toolbarController.PerfButton) && perfOverlayEnabled;
                ApplyActionChrome(chrome, foreground, surfaceMuted, border, active ? accent : surfaceMuted, active ? 0xFFFFFFFFu : foreground);
            }
        }
    }

    private static void ApplyActionChrome(Border chrome, uint foreground, uint surfaceMuted, uint border, uint background, uint textColor)
    {
        chrome.Background = CreateBrush(background);
        chrome.BorderBrush = CreateBrush(border);
        chrome.BorderThickness = new Thickness(1);

        if (chrome.Child is AvaPath path)
        {
            path.Fill = CreateBrush(textColor);
            return;
        }

        if (chrome.Child is TextBlock label)
        {
            label.Foreground = CreateBrush(textColor);
            return;
        }

        if (chrome.Child is Grid grid)
        {
            foreach (Control child in grid.Children.OfType<Control>())
            {
                if (child is AvaPath iconPath)
                {
                    iconPath.Fill = CreateBrush(textColor);
                }
                else if (child is Border badge && badge.Child is TextBlock badgeText)
                {
                    badge.Background = CreateBrush(textColor);
                    badgeText.Foreground = CreateBrush(surfaceMuted);
                }
            }
        }
    }

